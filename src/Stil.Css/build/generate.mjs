export function generateGrid() {
    const columns = suffix => Array.from({ length: 12 }, (_, i) =>
        `.stil-col${suffix}-${i + 1} { grid-column: span ${i + 1}; }`).join('\n');
    return [
        '/* Grid columns (generated) */',
        columns(''),
        ...Object.entries(breakpoints).map(([bp, width]) =>
            `@media (min-width: ${width}) {\n${indent(columns(`-${bp}`))}\n}`),
    ].join('\n');
}

export function generateVariants() {
    return ['/* Component variants (generated): set the color each component reads. */',
        ...variants.map(variant => {
            const selectors = variantComponents.map(c => `.stil-${c}-${variant}`).join(',\n');
            return `${selectors} {\n${variantDeclarations(variant)}\n}`;
        })].join('\n\n');
}

export function generateUtilities() {
    const base = [];
    const responsive = Object.fromEntries(Object.keys(breakpoints).map(bp => [bp, []]));

    for (const utility of utilities) {
        for (const [suffix, value] of Object.entries(utility.values)) {
            const properties = [utility.property].flat();
            const body = properties.map(p => `${p}: ${value};`).join(' ');
            const name = suffix === '' ? utility.prefix : `${utility.prefix}-${suffix}`;
            base.push(`.stil-${name} { ${body} }`);
            if (utility.responsive) {
                for (const bp of Object.keys(breakpoints)) {
                    const responsiveName = suffix === '' ? `${utility.prefix}-${bp}` : `${utility.prefix}-${bp}-${suffix}`;
                    responsive[bp].push(`.stil-${responsiveName} { ${body} }`);
                }
            }
        }
    }

    const variantUtilities = variants.flatMap(variant => [
        `.stil-bg-${variant} {\n${variantDeclarations(variant)}\n    background-color: var(--_bg);\n    color: var(--_fg);\n}`,
        `.stil-text-${variant} {\n${variantDeclarations(variant)}\n    color: var(--_ink);\n}`,
        `.stil-border-${variant} {\n${variantDeclarations(variant)}\n    border-color: var(--_ink);\n}`,
    ]);

    return [
        '/* Utilities (generated). Responsive variants: stil-{name}-{sm|md|lg|xl}-{value}. */',
        ...base,
        '',
        '/* Variant colors: background with readable text, text color, border color. */',
        ...variantUtilities,
        '',
        ...Object.entries(breakpoints).map(([bp, width]) =>
            `@media (min-width: ${width}) {\n${indent(responsive[bp].join('\n'))}\n}`),
    ].join('\n');
}

function variantDeclarations(variant) {
    return `    --_bg: var(--stil-color-${variant});\n    --_contrast: var(--stil-color-${variant}-contrast);`;
}

function spacing(prefix, property, scale) {
    const sides = {
        '': [property],
        t: [`${property}-top`],
        b: [`${property}-bottom`],
        s: [`${property}-inline-start`],
        e: [`${property}-inline-end`],
        x: [`${property}-inline`],
        y: [`${property}-block`],
    };
    return Object.entries(sides).map(([side, properties]) =>
        ({ prefix: prefix + side, property: properties, responsive: true, values: scale }));
}

function values(...names) {
    return Object.fromEntries(names.map(name => [name, name]));
}

function indent(text) {
    return text.split('\n').map(line => (line ? '    ' + line : line)).join('\n');
}
