namespace Stil.Blazor.Components;

/// <summary>
/// The color variants shared by Stil components. Each value maps to a
/// <c>stil-{component}-{variant}</c> CSS class, for example <c>stil-alert-danger</c>.
/// </summary>
public enum StilVariant
{
    Primary,
    Secondary,
    Success,
    Danger,
    Warning,
    Info
}
